  const key = 'christmas-lights-language';
  const excluded = 'script,style,pre,code,[data-no-translate]';
  const editable = 'textarea,[contenteditable]:not([contenteditable="false"])';
  const records = new WeakMap();
  const attributes = new WeakMap();
  const normalize = value => /^cs(?:-|$)/i.test(value || '') ? 'cs' : 'en';
  const preferred = () => normalize(navigator.languages?.[0] || navigator.language);
  let language = preferred();
  try { const saved = localStorage.getItem(key); if (saved === 'en' || saved === 'cs') language = saved; } catch {}
  const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = new RegExp(catalog.fragments.slice().sort((a,b) => b.length-a.length).map(value =>
    (/^[\p{L}\p{N}_]/u.test(value) ? '(?<![\\p{L}\\p{N}_])' : '') + escape(value) +
    (/[\p{L}\p{N}_]$/u.test(value) ? '(?![\\p{L}\\p{N}_])' : '')).join('|'), 'gu');
  function translate(source) {
    if (language === 'cs') return source;
    if (Object.hasOwn(catalog.messages, source)) return catalog.messages[source];
    // A device alias can itself be an interface word. Never translate the
    // interpolated address in this acknowledgement.
    const alias = source.match(/^Název uložen\. Po restartu: http:\/\/([a-z0-9-]+)\.local\/\. Záložní Wi-Fi i MQTT použijí nový název\.$/);
    if (alias) return 'Name saved. After restart: http://' + alias[1] + '.local/. Fallback Wi-Fi and MQTT will use the new name.';
    let result = source.replace(pattern, match => catalog.messages[match]);
    // These two live numeric labels are emitted using the original Czech locale.
    if (/^\d+,\d+ s$/.test(source) || source.startsWith('Pomalý cyklus trvá ')) result = result.replace(/(\d),(\d)/g,'$1.$2');
    return result;
  }
  function original(current, record) { return record && current === record.rendered ? record.source : current; }
  function text(node) {
    const parent = node.parentElement;
    if (!parent || parent.closest(excluded + ',' + editable)) return;
    const source = original(node.data, records.get(node));
    const trimmed = source.trim();
    let translated;
    // The browser title contains the literal device alias after the first poll.
    if (parent.tagName === 'TITLE' && source.endsWith(' · Světýlka'))
      translated = language === 'en' ? source.slice(0,-' · Světýlka'.length) + ' · Lights' : source;
    else translated = trimmed ? source.slice(0,source.indexOf(trimmed)) + translate(trimmed) + source.slice(source.indexOf(trimmed)+trimmed.length) : source;
    records.set(node,{source,rendered:translated});
    if (node.data !== translated) node.data = translated;
  }
  function element(el) {
    if (el.closest(excluded) || el.closest('[contenteditable]:not([contenteditable="false"])')) return;
    const saved = attributes.get(el) || {};
    for (const attr of ['placeholder','title','aria-label']) if (el.hasAttribute(attr)) {
      const source = original(el.getAttribute(attr),saved[attr]);
      const rendered = translate(source); saved[attr] = {source,rendered};
      if (el.getAttribute(attr) !== rendered) el.setAttribute(attr,rendered);
    }
    attributes.set(el,saved);
  }
  function visit(root) {
    if (root.nodeType === Node.TEXT_NODE) { text(root); return; }
    if (root.nodeType !== Node.ELEMENT_NODE || root.closest(excluded + ',' + editable)) return;
    element(root);
    for (const el of root.querySelectorAll('[placeholder],[title],[aria-label]')) element(el);
    const walker = document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) text(walker.currentNode);
  }
  const selector = document.getElementById('language');
  function refresh() {
    document.documentElement.lang = language;
    selector.value = language;
    visit(document.body); visit(document.querySelector('title'));
  }
